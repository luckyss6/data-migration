-- ============================================================================
-- 迁移清单：告诉程序要搬哪些表。这张表在【源库 Oracle】里。
--
-- 用法：
--   Get-Content .\db-test\02-oracle-config.sql -Raw |
--     docker exec -i oracle-test sqlplus -S source_user/source123@localhost:1521/ORCL
--
-- source_table 填源表名，目标表名 = 源表名 + 运行日期(20261014)：
--   orders      -> orders20261014
--   customers   -> customers20261014
--   products    -> products20261014
--   legacy      -> legacy20261014
--   empty_batch -> empty_batch20261014   (空表)
--   nots        -> 没有任何时间戳列，全量模式下正常工作
--   noid        -> 缺游标列 ID，解析阶段报 ERROR 跳过
--   tscol       -> TIMESTAMP 列搬不动，运行阶段 FAILED
--   missing     -> 源库里没有这张表，解析阶段报 WARN 跳过
--
-- 程序只读这张表、不会自动建表，所以这里（照抄 migration/db/sync_table_config.sql）建一次。
-- ============================================================================

declare
  v_exists number;
begin
  select count(*) into v_exists from user_tables where table_name = 'SYNC_TABLE_CONFIG';
  if v_exists = 0 then
    execute immediate 'CREATE TABLE sync_table_config ('
      || 'id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, '
      || 'source_table VARCHAR(100) NOT NULL, '
      || 'enabled NUMBER(1) DEFAULT 1 NOT NULL, '
      || 'remark VARCHAR(500) NULL, '
      || 'updated_at TIMESTAMP NULL, '
      || 'CONSTRAINT uk_sync_table_config_source UNIQUE (source_table))';
  end if;
end;
/

delete from sync_table_config;

insert into sync_table_config (source_table, remark) values ('orders',      '模拟数据：基础业务表，5000 行');
insert into sync_table_config (source_table, remark) values ('customers',   '模拟数据：类型矩阵表，2000 行');
insert into sync_table_config (source_table, remark) values ('products',    '模拟数据：复合主键表，600 行');
insert into sync_table_config (source_table, remark) values ('legacy',      '模拟数据：无主键表，300 行，靠 id-column 兜底');
insert into sync_table_config (source_table, remark) values ('empty_batch', '模拟数据：空表，0 行');
insert into sync_table_config (source_table, remark) values ('nots',        '正例：没有任何时间戳列，全量模式照搬');
insert into sync_table_config (source_table, remark) values ('noid',        '负例：源表缺 ID 列且无主键，应报 ERROR 跳过');
insert into sync_table_config (source_table, remark) values ('missing',     '负例：源库里没有这张表，应报 WARN 跳过');
insert into sync_table_config (source_table, remark) values ('tscol',       '负例：表里有 TIMESTAMP 普通列');

commit;

select source_table, enabled, remark from sync_table_config order by id;
