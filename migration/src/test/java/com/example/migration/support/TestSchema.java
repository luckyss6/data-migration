package com.example.migration.support;

import org.springframework.jdbc.core.JdbcTemplate;

/**
 * DDL the tests set up themselves. The application no longer creates any table of the source database,
 * {@code db/sync_table_config.sql} is the script a DBA runs - this is the H2 flavoured copy of it.
 */
public final class TestSchema {

	private TestSchema() {
	}

	/** Creates {@code sync_table_config} in the source database of the test. */
	public static void createSyncTableConfig(JdbcTemplate source) {
		source.execute("CREATE TABLE IF NOT EXISTS sync_table_config ("
				+ "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
				+ "source_table VARCHAR(100) NOT NULL, enabled SMALLINT DEFAULT 1 NOT NULL, "
				+ "remark VARCHAR(500) NULL, updated_at TIMESTAMP NULL, "
				+ "CONSTRAINT uk_sync_table_config_source UNIQUE (source_table))");
	}

}
