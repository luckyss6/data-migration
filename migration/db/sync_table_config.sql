-- 配置表：一行一个需要迁移的表。这张表建在【源库 Oracle】里。
--
-- 只有源库里真实存在的表才会被迁移：配了但源库里没有的表，每轮打 WARN 跳过，不影响其他表。
-- 程序只读这张表，不会自己建表，所以必须先执行本脚本（或由 DBA 走变更流程）把表建好。

CREATE TABLE sync_table_config (
    id           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_table VARCHAR(100) NOT NULL,
    enabled      NUMBER(1)    DEFAULT 1 NOT NULL,
    remark       VARCHAR2(500),
    updated_at   TIMESTAMP,
    CONSTRAINT uk_sync_table_config_source UNIQUE (source_table)
);

COMMENT ON TABLE  sync_table_config               IS 'Oracle -> MySQL 迁移的源表清单';
COMMENT ON COLUMN sync_table_config.source_table  IS '源表名(Oracle)，如 order；目标表名 = 源表名 + 运行日期，如 order20261014';
COMMENT ON COLUMN sync_table_config.enabled       IS '0 = 暂停这张表';
COMMENT ON COLUMN sync_table_config.remark        IS '备注';
COMMENT ON COLUMN sync_table_config.updated_at    IS '最后修改时间';

-- 示例：源表 order 会在运行时搬到 MySQL 的 order20261014
INSERT INTO sync_table_config (source_table, remark) VALUES ('order', '订单');
COMMIT;

